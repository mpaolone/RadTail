C    $HEADING CDIVIDE
      FUNCTION CDIVIDE(X,Y)
C     THIS ROUTINE IS MEANT TO DIVIDE 2 DOUBLE COMPLEX NUMBERS
C     WITHOUT THE PROBLEMS INHERENT WHEN BOTH NUMBERS ARE ABOUT SQRT
C     OF LARGEST REAL IN MAGNETUDE. THIS WILL NOT BE NECESSARY ON
C     MACHINES WITH LARGE POSSIBLE EXPONENENTS BUT IF THE
C     LARGEST POSSIBLE EXPONENT IN THE FLOATING POINT FORMAT
C     IS 77 AND SMALLER AS ON THE NORD-500, THEN THIS ROUTINE
C     IS REQUIRED
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      DOUBLE COMPLEX CDIVIDE,X,Y
      CDIVIDE=X
      XSIZ=DCABS(X)
      IF (XSIZ.EQ.0.0D0) RETURN
      XREL=DBLE(X)/XSIZ
      XIMA=DIMAG(X)/XSIZ
      YSIZ=DCABS(Y)
      IF (YSIZ.EQ.0.0D0) STOP 'DIVISION BY ZERO IN CDIVIDE'
      YREL=DBLE(Y)/YSIZ
      YIMA=DIMAG(Y)/YSIZ
      ZSIZ=XSIZ/YSIZ
      ZREL=ZSIZ*(XREL*YREL+XIMA*YIMA)
      ZIMA=ZSIZ*(XIMA*YREL-XREL*YIMA)
      CDIVIDE=DCMPLX(ZREL,ZIMA)
      RETURN
      END
C    $HEADING DCABS
      FUNCTION DCABS(X)
C     THIS ROUTINE RETURNS THE MAGNETUDE OF A COMPLEX NUMBER EVEN
C     UNDER EXTREMES OF THE EXPONENT VALUE OF THE MAGNETUDE.
C     THIS IS BECAUSE THE FOLLOWING ALGORYTHM IS USED:
C     MAG=MAX(R,I)*SQRT((R/MAX(R,I))**2+(I/MAX(R,I))**2)
C          IF MAX(R,I) IS GREATER THAN 1
C     MAG=MIN(R,I)*SQRT((R/MIN(R,I))**2+(I/MIN(R,I))**2)
C          IF MAX(R,I) IS LESS THAN 1
C     WHERE R AND I ARE ABSOLUTE VALUES OF THE REAL AND IMAG PARTS
C     MAG=SQRT(R**2+I**2)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      DOUBLE COMPLEX X
      REL=DABS(DBLE(X))
      DIM=DABS(DIMAG(X))
      D=DMAX1(REL,DIM)
      DCABS=0.0D0
      IF (D.EQ.0.0D0) RETURN
      IF (D.GT.1.0D0) GO TO 1
      C=DMIN1(REL,DIM)
      IF (C.NE.0.0D0) D=C
1     DCABS=D*DSQRT((REL/D)**2+(DIM/D)**2)
      RETURN
      END

      SUBROUTINE SPLINE(XIN,YIN,NMAX,XVAL,YVAL,ICTR)
C     Interpolation par les fonctions de SPLINE.
C     ICTR=0  Initialisation
C     ICTR=1 valeur d interpolation  YVAL au point XVAL.
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      DIMENSION XIN(NMAX),YIN(NMAX)
      DIMENSION XI(300),YI(300),DYI(300),B(300),IORD(300)

      IF(ICTR.GT.0) GOTO 20
CC    Initialisation. Ordonner en XI croissant de XIN    
      CALL ORDER(XIN,NMAX,IORD)
      DO 9 I=1,NMAX
      K=IORD(I)
      XI(I)=XIN(K)
9     YI(I)=YIN(K) 
      P=0.D0
      Q=0.D0
      H2=0.D0
      DO 10 I=1,NMAX
          H1=H2
          H12=H1*H1
          IF (I.LT.NMAX) THEN
              H2=1.D0/(XI(I+1)-XI(I))
          ELSE
              H2=0.D0
          ENDIF
          H22=H2*H2
          A=2.D0*(H1+H2)-P
          B(I)=H2/A
          DYI(I)=-3.D0*(YI(I-1)*H12+YI(I)*(H22-H12)-YI(I+1)*H22)
          DYI(I)=(DYI(I)-Q)/A
          P=B(I)*H2
          Q=DYI(I)*H2
10    CONTINUE
      P=0.D0
      DO 15 II=1,NMAX
          I=NMAX+1-II
          DYI(I)=DYI(I)-P*B(I)
          P=DYI(I)
15    CONTINUE
      RETURN

C     Valeur YVAL au point XVAL 
20    IF (XVAL.LT.XI(1)) GOTO 45
      IF (XVAL.GT.XI(NMAX)) GOTO 40
      DO 30 I=2,NMAX
      XN=XVAL-XI(I)
      IF(XN.LT.0.D0) THEN
         XM=XVAL-XI(I-1)
         H=1.D0/(XI(I)-XI(I-1))
         A1=DYI(I)-2.D0*YI(I)*H
         A2=DYI(I-1)+2.D0*YI(I-1)*H
         B1=A1*XN+YI(I)
         B2=A2*XM+YI(I-1)
         XM2=XM*XM
         XN2=XN*XN
         H2=H*H
         YVAL=H2*(XM2*B1+XN2*B2)
         RETURN
      ELSEIF (XN.EQ.0.D0) THEN
         YVAL=YI(I)
         RETURN
      ENDIF
30    CONTINUE
40    YVAL=YI(NMAX)+(XVAL-XI(NMAX))*DYI(NMAX)
      RETURN
45    YVAL=YI(1)+(XVAL-XI(1))*DYI(1)
      RETURN
      END

